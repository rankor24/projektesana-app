// Writes src/shared/app-catalog.generated.ts from the IPC contract (src/shared/api.ts, interface ApiSpec): each call's parameters,
// result type and its doc comment, for the agent's app_calls tool (the types do not exist at run time). Run by `npm run build`;
// `node scripts/gen-app-catalog.mjs --check` fails when the file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const api = readFileSync(join(root, "src", "shared", "api.ts"), "utf8").replace(/\r\n/g, "\n");
const start = api.indexOf("export interface ApiSpec {");
if (start < 0) throw new Error("ApiSpec not found in src/shared/api.ts");
let depth = 0;
let end = start;
for (let i = api.indexOf("{", start); i < api.length; i++) {
	if (api[i] === "{") depth++;
	else if (api[i] === "}" && --depth === 0) {
		end = i;
		break;
	}
}
const body = api.slice(api.indexOf("{", start) + 1, end);

const out = {};
let doc = "";
const lines = body.split("\n");
for (let i = 0; i < lines.length; i++) {
	const l = lines[i].trim();
	if (l.startsWith("/**")) {
		let c = l;
		while (!c.includes("*/") && i + 1 < lines.length) c += ` ${lines[++i].trim()}`;
		doc = c.replace(/^\/\*\*|\*\/$/g, "").replace(/\s*\*\s*/g, " ").trim();
		continue;
	}
	const m = /^"([\w.]+)":\s*(.*)$/.exec(l);
	if (!m) {
		if (l && !l.startsWith("//")) doc = "";
		continue;
	}
	let sig = m[2];
	// a signature over several lines ends at the first ';' outside brackets
	const closed = (s) => {
		let d = 0;
		for (const ch of s) {
			if ("([{<".includes(ch)) d++;
			else if (")]}>".includes(ch) && !(ch === ">" && s.includes("=>") && d === 0)) d--;
		}
		return s.trimEnd().endsWith(";") && d <= 0;
	};
	while (!closed(sig) && i + 1 < lines.length) sig += ` ${lines[++i].trim()}`;
	sig = sig.replace(/;\s*$/, "").replace(/\s+/g, " ");
	const params = /^\(([^)]*)\)/.exec(sig)?.[1] ?? "";
	const names = params
		.split(/,(?![^{]*\})/)
		.map((p) => p.trim().split(/[?:]/)[0].trim())
		.filter(Boolean);
	out[m[1]] = { sig, params: names, ...(doc ? { doc } : {}) };
	doc = "";
}

const text = `// Generated by scripts/gen-app-catalog.mjs from src/shared/api.ts (ApiSpec). Do not edit: run npm run build.\nexport const APP_CATALOG: Record<string, { sig: string; params: string[]; doc?: string }> = ${JSON.stringify(out, null, "\t")};\n`;
const file = join(root, "src", "shared", "app-catalog.generated.ts");
if (process.argv.includes("--check")) {
	if (readFileSync(file, "utf8") !== text) {
		console.error("app-catalog.generated.ts is out of date: run node scripts/gen-app-catalog.mjs");
		process.exit(1);
	}
} else writeFileSync(file, text);
console.log(`app catalog: ${Object.keys(out).length} calls`);
